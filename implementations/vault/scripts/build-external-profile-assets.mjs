// Reproduce the browser/SDK's trusted profile assets from this app's pinned files.
// No network, compilation, proving or deployment.
import fs from 'node:fs';
import {sha256} from 'ethers';
const base=new URL('../',import.meta.url),read=p=>fs.readFileSync(new URL(p,base)),json=p=>JSON.parse(read(p));
const perf05=json('external-proofs/perf05/descriptor.json');
const policy=json('proof/manifest.json'),deployment=json('proof/deployment.json');
if(deployment.profileId!==policy.profileId||deployment.args[0]!==policy.imageId)throw Error('v3 descriptor mismatch');
const v3={tag:'v3',label:'v3 · Lean / Nat, три аксиомы',description:'Исходный неизменённый профиль Lean 4.33.1 / NanoDa: pinned Nat и три аксиомы foundation. Внешний сертификат должен соответствовать именно этому image.',
 profileId:policy.profileId,imageId:policy.imageId,foundationSha256:policy.foundationSha256,
 selector:perf05.selector,verifierParameters:perf05.verifierParameters,manifest:deployment.manifest,lean:policy.lean,goals:[]};
const entries=[[perf05,'external-proofs/perf05/fixtures/foundation.ndjson'],[v3,'proof/lean/foundation.ndjson']].map(([descriptor,path])=>{
 const bytes=read(path),foundationSha256=descriptor.foundationSha256||JSON.parse(descriptor.manifest).foundationSha256;
 if(sha256(bytes).slice(2)!==foundationSha256)throw Error('Foundation pin mismatch: '+path);
 return {descriptor:{...descriptor,foundationSha256},foundationBase64:bytes.toString('base64'),foundationPath:path};
});
fs.writeFileSync(new URL('sdk/external-profile-assets.mjs',base),'// Generated by scripts/build-external-profile-assets.mjs from pinned app-local files.\n// Contains profile policy/foundation, never an allowlist of generic theorem hashes.\nexport const externalProfileAssets = '+JSON.stringify(entries,null,2)+';\n');
console.log('Wrote '+entries.length+' trusted profile/foundation assets; no chain calls.');
